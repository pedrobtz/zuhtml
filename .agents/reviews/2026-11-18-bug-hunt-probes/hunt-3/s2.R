source("pre.R")
doc <- html_parse('<html><body><div id=a><div id=b><p id=p1>x</p><template id=t><p id=tp>in<span id=ts>s</span></p></template><div id=c><p id=p2>y</p></div></div></div><p id=p3>z</p>')
a <- html_element(doc, "#a"); b <- html_element(doc, "#b")
cat("from a 'div p':", sel(a, "div p"), "\n")      # p1,p2 (div ancestor may be outside scope? yes selectors match against whole doc)
cat("from b 'div p':", sel(b, "div p"), "\n")      # p1,p2 (matches as querySelectorAll)
cat("from b ':scope p':", sel(b, ":scope p"), "\n")
cat("from b ':scope > p':", sel(b, ":scope > p"), "\n")
cat("from b ':scope':", sel(b, ":scope"), "\n")
cat("from b ':scope ~ p':", sel(b, ":scope ~ p"), "\n")
cat("from b '#a p':", sel(b, "#a p"), "\n")
cat("from b 'body > div p':", sel(b, "body > div p"), "\n")
cat("from b ':root p':", sel(b, ":root p"), "\n")
cat("doc 'template p':", sel(doc, "template p"), "\n")
cat("doc '#tp':", sel(doc, "#tp"), "\n")
tc <- html_template_content(html_element(doc, "template"))
print(tc); cat("tc 'p':", sel(tc, "p"), " span:", sel(tc,"p span"), " scope:", sel(tc, ":scope"), " tmpl p:", sel(tc,"template p"), "root:", sel(tc, ":root"),"\n")
tp <- try_(html_elements(tc, "p")); print(tp)
cat("tp parent:", html_name(html_parent(tp)), " closest div:", html_attr(html_closest(tp, "div"), "id"), " ancestors:", paste(html_name(html_ancestors(tp)), collapse=","), "\n")
cat("tp matches 'template p':", html_matches(tp, "template p"), " '#a p':", html_matches(tp, "#a p"), "\n")
cat("text of b:", html_text(b), "| clean:", html_text_clean(b), "| template text:", html_text(html_element(doc,"template")), "| tp:", html_text(tp), "\n")
cat("p:first-child in tc:", sel(tc, "p:first-child"), " nth:", sel(tc, ":nth-child(1)"), "\n")
