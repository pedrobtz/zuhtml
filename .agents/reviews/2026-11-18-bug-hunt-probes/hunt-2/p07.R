source("pre.R")
res <- function(expr) { v <- tryCatch(expr, error=function(e) e); if (inherits(v,"error")) paste0("ERR ", class(v)[1], " ", v$limit, " obs=", format(v$observed)) else paste0("ok nodes=", html_info(v)$nodes) }
maxdepth <- function(d) { # deepest element depth: ancestors count incl. itself below document
  e <- html_elements(d, "*"); max(lengths(lapply(seq_along(e), function(i) html_ancestors(e[i])))) + 1 }
nest <- function(tag, k, inner = "") paste0(strrep(paste0("<", tag, ">"), k), inner)
D <- 10; Ld <- html_limits(max_depth = D)
cat("== document: html>body>div^k ; element depth = k+2\n")
for (k in 6:10) cat(k, res(html_parse(nest("div", k), limits = Ld)), "| with text:", res(html_parse(nest("div", k, "x"), limits = Ld)), "\n")
cat("== fragment(div): div^k ; R-visible depth = k\n")
for (k in 7:11) cat(k, res(html_fragment(nest("div", k), limits = Ld)), "| text:", res(html_fragment(nest("div", k, "x"), limits = Ld)), "\n")
cat("== fragment(template)\n")
for (k in 7:11) cat(k, res(html_fragment(nest("div", k), "template", limits = Ld)), "\n")
cat("== template in doc: html>body>template>div^k -> depth k+3\n")
for (k in 5:9) cat(k, res(html_parse(paste0("<template>", nest("div", k)), limits = Ld)), "\n")
cat("== template in head (default placement): html>head>template>div^k\n")
for (k in 5:9) cat(k, res(html_parse(paste0("<!doctype html><template>", nest("div", k)), limits = Ld)), "\n")
cat("== svg: html>body>svg>g^k -> k+3\n")
for (k in 5:9) cat(k, res(html_parse(paste0("<svg>", nest("g", k)), limits = Ld)), "\n")
cat("== formatting b^k\n")
for (k in 6:10) cat(k, res(html_parse(nest("b", k), limits = Ld)), "\n")
cat("== table nesting: table>tbody>tr>td implied\n")
for (k in 1:4) cat(k, res(html_parse(strrep("<table><td>", k), limits = Ld)), "\n")
cat("== adoption agency deep: <a><div>... \n")
for (k in 3:9) cat(k, res(html_parse(paste0(strrep("<b><p>", k), strrep("</b>", k)), limits = Ld)), "\n")
cat("== actual depth at passing boundary\n")
print(maxdepth(html_parse(nest("div", 8), limits = Ld)))
cat("== default 512 boundary\n")
for (k in 509:512) cat(k, res(html_parse(nest("div", k))), " frag:", res(html_fragment(nest("div", k))), "\n")
cat("== depth 1,2,3 trivial doc\n")
for (d in 1:4) cat(d, res(html_parse("", limits = html_limits(max_depth = d))), res(html_parse("x", limits = html_limits(max_depth = d))), "frag:", res(html_fragment("x", limits = html_limits(max_depth = d))), res(html_fragment("<p>x", limits = html_limits(max_depth = d))), "\n")

cat("== max_nodes\n")
d <- html_parse("<p>a<!--c--><b>x</b>"); n <- html_info(d)$nodes; cat("nodes", n, "\n")
for (m in (n-1):(n+1)) cat(m, res(html_parse("<p>a<!--c--><b>x</b>", limits = html_limits(max_nodes = m))), "\n")
d <- html_parse("<p>a<!--c--><b>x</b>", comments = FALSE); n <- html_info(d)$nodes; cat("nodes no comments", n, "\n")
for (m in (n-1):(n+1)) cat(m, res(html_parse("<p>a<!--c--><b>x</b>", comments = FALSE, limits = html_limits(max_nodes = m))), "\n")
d <- html_fragment("<p>a<!--c--><b>x</b>"); n <- html_info(d)$nodes; cat("fragment nodes", n, "\n")
for (m in (n-1):(n+1)) cat(m, res(html_fragment("<p>a<!--c--><b>x</b>", limits = html_limits(max_nodes = m))), "\n")
d <- html_fragment("<!--a--><!--b--><!--c-->x", comments=FALSE); n <- html_info(d)$nodes; cat("fragment nodes comments off", n, "\n")
for (m in (n-1):(n+1)) cat(m, res(html_fragment("<!--a--><!--b--><!--c-->x", comments=FALSE, limits = html_limits(max_nodes = m))), "\n")
d <- html_parse("<!doctype html><template><p>x</template>"); n <- html_info(d)$nodes; cat("template nodes", n, "\n")
for (m in (n-1):(n+1)) cat(m, res(html_parse("<!doctype html><template><p>x</template>", limits = html_limits(max_nodes = m))), "\n")

cat("== max_errors\n")
src <- "<p></x></y></z>"
for (m in 0:4) { d <- html_parse(src, limits = html_limits(max_errors = m)); p <- html_problems(d); cat(m, "rows", nrow(p), "trunc", attr(p, "truncated"), "info", html_info(d)$problems, html_info(d)$problems_truncated, "\n") }
print(html_problems(html_parse(src)))
