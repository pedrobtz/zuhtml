# Each: prefix + byte E9. latin1 -> U+00E9 ; koi8-r -> U+0418 ; none -> encoding error
t <- function(prefix, expect) { d <- try_(html_parse(c(s(prefix), s("<p id=t>"), r(0xe9), s("</p>")))); got <- if (inherits(d, "err")) "none" else { cpt <- utf8ToInt(html_text(html_element(d, "#t"))); if (identical(cpt, 0xE9L)) "latin1" else if (identical(cpt, 0x418L)) "koi8-r" else paste(html_info(d)$encoding, sprintf("%04X", cpt)) }; cat(sprintf("%-6s %-8s %-8s %s\n", if (got == expect) "ok" else "DIFF", expect, got, prefix)) }
t('<meta charset=latin1>', "latin1")
t('<META CHARSET=LATIN1>', "latin1")
t('<meta charset = "latin1" >', "latin1")
t("<meta charset='latin1'/>", "latin1")
t('<meta/charset=latin1>', "latin1")
t('<metadata charset=latin1>', "none")
t('<meta charset=latin1', "none")
t('<meta charset=latin1 charset=koi8-r>', "latin1")
t('<meta content="text/html; charset=koi8-r" charset=latin1>', "latin1")
