source("h.R")
# JSON-LD: body that is a file path
f <- tempfile(fileext = ".json"); writeLines('{"secret": "local file content"}', f)
d <- html_parse(sprintf('<script type="application/ld+json">%s</script>', f))
p("jsonld path", html_json_ld(d, parse = TRUE))
d <- html_parse('<script type="application/ld+json">"just a string"</script><script type="application/ld+json">[1,2]</script><script type="application/ld+json">{bad</script>')
p("jsonld misc", html_json_ld(d, parse = TRUE))
# sniff with high bytes in charset label
x <- c(charToRaw('<meta charset="'), as.raw(c(0xe9, 0xff)), charToRaw('"><p>hi'))
p("sniff highbyte charset", html_info(html_parse(x))$encoding)
x <- c(charToRaw('<meta http-equiv="content-type" content="text/html; charset='), as.raw(c(0xe9)), charToRaw('"><p>hi'))
p("sniff highbyte content", html_info(html_parse(x))$encoding)
x <- c(charToRaw('<meta '), as.raw(0xe9), charToRaw('="1" charset="latin1"><p>hi'), as.raw(0xe9))
p("sniff highbyte attrname", html_text(html_parse(x)))
# forms: form attr with newline
d <- html_parse('<form id="a"></form><input form="a&#10;b" name="q">')
p("forms newline ref", html_forms(d))
d <- html_parse('<form id=\'a"b\\c\'></form><input form=\'a"b\\c\' name="q">')
p("forms quote ref", html_forms(d)[[1]]$fields)
# OutDec prints
d <- html_parse("<p>x")
options(OutDec = ",")
p("print info OutDec", print(html_info(d)))
p("print limits OutDec", print(html_limits()))
options(warn = 2)
p("print info OutDec warn2", print(html_info(d)))
p("print limits OutDec warn2", print(html_limits()))
options(OutDec = ".", warn = 0)
# selector position multibyte
